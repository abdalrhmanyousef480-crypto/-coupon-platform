async function main() {
  const author = await db.user.findFirst({ where: { role: "ADMIN" }, orderBy: { createdAt: "asc" }, select: { id: true } });
  if (!author) throw new Error("لا يوجد مستخدم ADMIN لنسب المقالات إليه");

  for (const a of ARTICLES) {
    const store = await db.store.findUnique({
      where: { slug: a.storeSlug },
      select: { logoUrl: true, categories: { orderBy: { createdAt: "asc" }, take: 1, select: { categoryId: true } } },
    });
    if (!store) { console.log(`✗ ${a.slug}: المتجر "${a.storeSlug}" غير موجود — تخطّي`); process.exitCode = 1; continue; }

    if (await db.article.findUnique({ where: { slug: a.slug }, select: { id: true } })) {
      console.log(`= ${a.slug}: موجود مسبقًا — لم يُلمس`);
      continue;
    }

    const now = new Date();
    await db.article.create({
      data: {
        slug: a.slug,
        title: "",
        titleAr: a.titleAr,
        excerpt: "",
        excerptAr: a.excerptAr,
        content: "",
        contentAr: a.content.join("\n\n"),
        featuredImage: store.logoUrl, // نفس اصطلاح غيم: شعار المتجر
        status: "PUBLISHED",
        publishedAt: now,
        authorId: author.id,
        categoryId: store.categories[0]?.categoryId ?? null,
        seoTitleAr: a.seoTitleAr,
        seoDescriptionAr: a.seoDescriptionAr,
      },
    });
    console.log(`✓ ${a.slug}: أُنشئ (PUBLISHED)`);
  }
}

main().catch((e) => { console.error("✗", (e as Error).message.split("\n")[0]); process.exitCode = 1; }).finally(() => db.$disconnect());
