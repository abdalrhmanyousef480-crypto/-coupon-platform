-- ============================================================
-- الكوبونات: إلغاء "تثبيت" التصنيف المنسوخ من المتجر
-- ============================================================
-- سابقًا كان createCoupon/updateCoupon ينسخ تصنيف المتجر الوحيد إلى
-- coupons.categoryId عند غياب اختيار صريح. مع المتجر متعدد التصنيفات،
-- هذا النسخ كان سيثبّت الكوبون على تصنيف واحد فقط ويخفيه من بقية
-- تصنيفات متجره.
--
-- منطق العرض (category-coupons.ts) يعتبر coupons.categoryId = NULL معناه
-- "يرث تصنيفات المتجر". فهنا نحوّل فقط الكوبونات اللي categoryId عندها
-- يساوي أحد تصنيفات متجرها الحالية إلى NULL — النتيجة الفعلية للعرض
-- لكل كوبون كانت وتبقى نفسها اليوم (المتجر عنده تصنيف واحد بعد الـ
-- backfill)، وأي override حقيقي لتصنيف مختلف عن تصنيفات المتجر يبقى كما هو.
--
-- مسار الرجوع: القيمة القديمة قابلة للاسترجاع دائمًا من stores.categoryId
-- (العمود القديم لم يُحذف).
--
-- يجب تنفيذه بعد 20260920_store_categories_many_to_many.sql. idempotent.
-- ============================================================

UPDATE "coupons" c
SET "categoryId" = NULL
FROM "store_categories" sc
WHERE sc."storeId" = c."storeId"
  AND sc."categoryId" = c."categoryId";
